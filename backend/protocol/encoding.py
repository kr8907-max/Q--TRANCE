"""Deterministic derivation of the reference signature-state sequence.

This module is the **replaceable** mapping between a message binding and the
sequence of qubit states the protocol transmits. It is deliberately isolated:
everything above it treats a sequence as "whatever :func:`derive_state_sequence`
returns", so the mapping can be swapped without touching the signer, the
verifier or the transcript format.

This mapping is an *engineering choice* for the reference prototype. It is not
a security construction, and it makes no claim to be one.

The alphabet
------------
The six states are exactly the Pauli eigenstates implemented and tested in
:mod:`backend.quantum.states`. The canonical ordering is taken from that
module's ``EIGENSTATE_LABELS``, so the alphabet cannot drift from the quantum
core::

    index   identifier   ket      basis   eigenvalue
    0       Z+           |0>      Z       +1
    1       Z-           |1>      Z       -1
    2       X+           |+>      X       +1
    3       X-           |->      X       -1
    4       Y+           |+i>     Y       +1
    5       Y-           |-i>     Y       -1

The derivation
--------------
1. ``message_binding`` is 32 bytes of SHA-256 output, used as the seed.
2. Blocks are generated by counter-mode SHA-256::

       block_k = SHA256( seed || UTF8("rqds-tp-1.0/state-stream") || uint32_be(k) )

   ``k`` starts at 0 and increases by one. The domain tag separates this byte
   stream from every other digest in the protocol.
3. Each block is consumed as sixteen 4-bit nibbles, most significant first.
4. A nibble ``n < 12`` is accepted and yields alphabet index ``n mod 6``.
   Nibbles ``12..15`` are discarded. Because ``12 = 2 * 6``, the accepted range
   contains each residue class exactly twice, so the mapping is **unbiased**
   over the six states -- unlike a naive ``byte mod 6``, which would favour
   four of the six.

Determinism and state
---------------------
The derivation is a pure function of ``(binding, count)``. There is no global
state, no clock and no randomness, so the same binding always produces the same
sequence. Rejection sampling consumes a variable number of nibbles, which is
still deterministic because the stream itself is deterministic.
"""

from __future__ import annotations

import hashlib
from typing import Any, Dict, Iterator, Tuple

from backend.quantum.states import EIGENSTATE_LABELS, get_eigenstate

from backend.protocol.models import ProtocolValidationError, SignatureState

__all__ = [
    "STREAM_DOMAIN",
    "STATE_ALPHABET",
    "ALPHABET_SIZE",
    "NIBBLE_ACCEPT_LIMIT",
    "identifier_for_label",
    "state_for_identifier",
    "state_from_alphabet_index",
    "nibble_stream",
    "derive_alphabet_indices",
    "derive_state_sequence",
    "sequence_metadata",
]


STREAM_DOMAIN = "rqds-tp-1.0/state-stream"


STATE_ALPHABET: Tuple[str, ...] = tuple(
    f"{get_eigenstate(label).basis}"
    f"{'+' if get_eigenstate(label).eigenvalue > 0 else '-'}"
    for label in EIGENSTATE_LABELS
)

ALPHABET_SIZE = len(STATE_ALPHABET)


NIBBLE_ACCEPT_LIMIT = 2 * ALPHABET_SIZE


def identifier_for_label(label: str) -> str:
    """Return the canonical symbolic identifier for an eigenstate label."""
    state = get_eigenstate(label)
    return f"{state.basis}{'+' if state.eigenvalue > 0 else '-'}"


def state_for_identifier(identifier: str) -> SignatureState:
    """Return the :class:`SignatureState` for a canonical identifier."""
    if identifier not in STATE_ALPHABET:
        raise ProtocolValidationError(
            f"unknown state identifier {identifier!r}; expected one of "
            f"{list(STATE_ALPHABET)}"
        )
    label = EIGENSTATE_LABELS[STATE_ALPHABET.index(identifier)]
    state = get_eigenstate(label)
    return SignatureState(
        index=-1,
        basis=state.basis,
        label=state.label,
        eigenvalue=int(state.eigenvalue),
        state_identifier=identifier,
    )


def state_from_alphabet_index(index: int, position: int) -> SignatureState:
    """Return the ``position``-th signature state for alphabet ``index``."""
    if not 0 <= index < ALPHABET_SIZE:
        raise ProtocolValidationError(
            f"alphabet index must lie in [0, {ALPHABET_SIZE}), got {index}"
        )
    template = state_for_identifier(STATE_ALPHABET[index])
    return SignatureState(
        index=position,
        basis=template.basis,
        label=template.label,
        eigenvalue=template.eigenvalue,
        state_identifier=template.state_identifier,
    )


def nibble_stream(seed: bytes) -> Iterator[int]:
    """Yield the unbounded deterministic nibble stream for ``seed``."""
    if not isinstance(seed, (bytes, bytearray)):
        raise ProtocolValidationError(
            f"seed must be bytes, got {type(seed).__name__}"
        )
    domain = STREAM_DOMAIN.encode("utf-8")
    counter = 0
    while True:
        block = hashlib.sha256(bytes(seed) + domain + counter.to_bytes(4, "big")).digest()
        for byte in block:
            yield byte >> 4
            yield byte & 0x0F
        counter += 1


def derive_alphabet_indices(binding: str, count: int) -> Tuple[int, ...]:
    """Return ``count`` unbiased alphabet indices derived from ``binding``."""
    if not isinstance(binding, str) or len(binding) != 64:
        raise ProtocolValidationError(
            "message binding must be a 64-character lowercase hex SHA-256 digest"
        )
    if any(character not in "0123456789abcdef" for character in binding):
        raise ProtocolValidationError(
            "message binding must be lowercase hex"
        )
    if not isinstance(count, int) or isinstance(count, bool) or count < 1:
        raise ProtocolValidationError(f"count must be a positive int, got {count!r}")

    seed = bytes.fromhex(binding)
    indices = []
    stream = nibble_stream(seed)
    while len(indices) < count:
        nibble = next(stream)
        if nibble < NIBBLE_ACCEPT_LIMIT:
            indices.append(nibble % ALPHABET_SIZE)
    return tuple(indices)


def derive_state_sequence(binding: str, count: int) -> Tuple[SignatureState, ...]:
    """Return the reference signature-state sequence for ``binding``."""
    return tuple(
        state_from_alphabet_index(index, position)
        for position, index in enumerate(derive_alphabet_indices(binding, count))
    )


def sequence_metadata(count: int, binding: str) -> Dict[str, Any]:
    """Return the public metadata describing how a sequence was derived.

    The metadata records *how* to reproduce the sequence. It deliberately does
    **not** contain the sequence itself: the verifier must derive the states
    from the binding rather than read them out of a declaration.
    """
    return {
        "derivation": "sha256-counter-mode-nibble-rejection",
        "stream_domain": STREAM_DOMAIN,
        "alphabet": list(STATE_ALPHABET),
        "alphabet_size": ALPHABET_SIZE,
        "nibble_accept_limit": NIBBLE_ACCEPT_LIMIT,
        "state_count": count,
        "binding_digest_length": len(binding),
    }
